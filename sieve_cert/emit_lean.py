"""Write lean/Fermat433/Sieve/Data.lean from sieve_cert/inputs.txt.

Besides the inputs, the Lean file carries, for every candidate removed at a prime, a *removal
witness*: the fibre {Q in E1(F_q) : c1*Q = T1} over the candidate's target T1, and for each Q a
square root of u/A (of f(x-) when Q = O), or the marker q when there is none. These are cheap to check
and expensive to find. The checker trusts none of them; a wrong witness makes it fail.

Usage: python3 sieve_cert/emit_lean.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from check import F1, ELL, Field, Curve, peval, pmul, read_inputs  # noqa: E402


def removals(data, q, r, alive):
    """Removal witnesses at the prime (q, t - r) for the candidates in `alive`; returns (witnesses, still alive)."""
    K = Field(q)
    ev = lambda cs: sum(K.frac(c) * pow(r, k, q) for k, c in enumerate(cs)) % q
    xp, xm = ev(data["XP"]), ev(data["XM"])
    F = [0] * 7
    for k, c in enumerate(F1):
        term = [c % q]
        for _ in range(k):
            term = pmul(term, [(-xp) % q, xm], q)
        for _ in range(6 - k):
            term = pmul(term, [q - 1, 1], q)
        F = [(u + v) % q for u, v in zip(F, term)]
    D, C, B, A = F[0], F[2], F[4], F[6]
    E1, E2 = Curve(K, B, A * C, A * A * D), Curve(K, C, B * D, A * D * D)
    c1, c2 = E1.order() // ELL, E2.order() // ELL
    sq = {}
    for y in range(q):
        sq.setdefault(y * y % q, y)
    inv = K.inv

    def phi(x, y):
        if x == xm:
            return None, (0, D * y % q)
        if x == xp:
            return (0, -A * y % q), None
        X = (x - xp) * inv(x - xm) % q
        Y = y * pow(X - 1, 3, q) % q
        return (A * X * X % q, A * Y % q), (D * inv(X * X) % q, D * Y * inv(pow(X, 3, q)) % q)

    G = [phi(1, 1), phi(q - 1, 15)]
    G = [(E1.mul(c1, g[0]), E2.mul(c2, g[1])) for g in G]
    fibres = {}                                      # c1*Q -> [Q]
    pts = [None] + [(x, y) for x in range(q) for y in {sq.get(E1.rhs(x)), (-sq.get(E1.rhs(x), 0)) % q}
                    if sq.get(E1.rhs(x)) is not None]
    for Q in pts:
        fibres.setdefault(E1.mul(c1, Q), []).append(Q)

    def over(Q):                                     # (witness, images under c2*phi2) of the X-points over Q
        if Q is None:
            fx = peval([c % q for c in F1], xm, q)
            w = sq.get(fx, q)
            imgs = [] if w == q else [(0, D * w % q), (0, -D * w % q)]
        else:
            u, v = Q
            s = u * inv(A) % q
            Y = v * inv(A) % q
            w = sq.get(s, q)
            imgs = [] if w == q else [None if X == 0 else (D * inv(X * X) % q, D * Y * inv(pow(X, 3, q)) % q)
                                      for X in (w, (-w) % q)]
        return w, [E2.mul(c2, P) for P in imgs]

    out, still = [], []
    for a in alive:
        T1 = E1.add(E1.mul(a[0], G[0][0]), E1.mul(a[1], G[1][0]))
        T2 = E2.add(E2.mul(a[0], G[0][1]), E2.mul(a[1], G[1][1]))
        fib = fibres.get(T1, [])
        assert len(fib) == c1
        data_q = [(Q, *over(Q)) for Q in fib]
        if any(T2 in imgs for _, _, imgs in data_q):
            still.append(a)
        else:
            out.append((a, [(Q, w) for Q, w, _ in data_q]))
    print(f"q={q} r={r}: c1={c1} c2={c2} removed {len(out)}, still alive {len(still)}")
    return out, still


def lean_pt(Q):
    return ".inf" if Q is None else f".pt {Q[0]} {Q[1]}"


def lean_list(xs, per_line=24, indent="    "):
    xs = [str(x) for x in xs]
    rows = [", ".join(xs[i:i + per_line]) for i in range(0, len(xs), per_line)]
    return "[" + (",\n" + indent).join(rows) + "]"


def frac_list(fs):
    return "[" + ", ".join(f"({f.numerator}, {f.denominator})" for f in fs) + "]"


def main():
    root = os.path.join(os.path.dirname(__file__), "..")
    data = read_inputs(os.path.join(root, "sieve_cert", "inputs.txt"))
    out = [
        "/-",
        "Copyright (C) 2026 Marcello Federico",
        "SPDX-License-Identifier: GPL-3.0-or-later",
        "",
        "GENERATED by sieve_cert/emit_lean.py from sieve_cert/inputs.txt. Do not edit by hand.",
        "-/",
        "import Fermat433.Sieve.Check",
        "",
        "set_option maxRecDepth 200000",
        "",
        "namespace Fermat433.Sieve",
        "",
        "/-- The exact inputs of the sieve for `B⁻`, exported by `sieve_cert/emit.gp`. -/",
        "def inputs : Inputs where",
        f"  pl := {data['PL']}",
        f"  xp := {frac_list(data['XP'])}",
        f"  xm := {frac_list(data['XM'])}",
        f"  cands := {lean_list([f'({a}, {b})' for _, _, a, b in data['cands']], 12)}",
        "",
    ]
    names = []
    alive = [(a, b) for _, _, a, b in data["cands"]]
    for q, r in data["primes"]:
        rem, alive = removals(data, q, r, alive)
        name = f"cert{q}"
        names.append(name)
        entries = [f"⟨({a[0]}, {a[1]}), [{', '.join(f'({lean_pt(Q)}, {w})' for Q, w in fib)}]⟩"
                   for a, fib in rem]
        out += [
            f"/-- Removal witnesses at the prime of `L` above {q} given by `t ↦ {r}`. -/",
            f"def {name} : PrimeCert where",
            f"  q := {q}",
            f"  r := {r}",
            "  removals := [\n    " + ",\n    ".join(entries) + "]",
            "",
        ]
    print("survivors:", alive)
    out += [f"def certs : List PrimeCert := [{', '.join(names)}]", "", "end Fermat433.Sieve", ""]
    path = os.path.join(root, "lean", "Fermat433", "Sieve", "Data.lean")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    main()
